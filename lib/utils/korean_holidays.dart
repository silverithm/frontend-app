  static String _toKey(DateTime date) {
    final y = date.year.toString().padLeft(4, '0');
    final m = date.month.toString().padLeft(2, '0');
    final d = date.day.toString().padLeft(2, '0');
    return '$y-$m-$d';
  }

  /// 공휴일이면 이름을, 아니면 null을 반환한다
  static String? getHolidayName(DateTime date) => _holidays[_toKey(date)];

  /// 법정 공휴일 여부 (일·토요일은 포함하지 않는다 — 요일 색은 별도 처리)
  static bool isHoliday(DateTime date) => _holidays.containsKey(_toKey(date));
