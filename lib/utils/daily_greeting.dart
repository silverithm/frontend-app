/// 오늘의 인사말 — 날짜(연중 일수) 기준으로 매일 다른 멘트를 돌려준다.
///
/// frontend-admin의 `getDailyGreeting(date: Date = new Date())`와 동일한 계산식.
/// JS `new Date(year, 0, 0)`(1월 0일 = 전년도 12월 31일)을 Dart로 옮기면
/// 월이 1-indexed이므로 `DateTime(year, 1, 0)`이 된다 — `DateTime(year, 0, 0)`을
/// 쓰면 다른 날짜로 정규화되어 웹과 문구가 어긋나므로 주의.
String getDailyGreeting([DateTime? date]) {
  final d = date ?? DateTime.now();
  final start = DateTime(d.year, 1, 0);
  final dayOfYear =
      ((d.millisecondsSinceEpoch - start.millisecondsSinceEpoch) / 86400000)
          .floor();
  return _dailyMessages[dayOfYear % _dailyMessages.length];
}
